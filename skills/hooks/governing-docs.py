#!/usr/bin/env python3
"""governing-docs.py: the one test for whether a file is documentation, the
governing prose an edit needs the owner's permission for. Three hooks ask it:
warn-governing-docs.sh after each edit, session-detail-caption.py of each file a
session changed (to count the edits still waiting on the owner's sign-off), and
commit-consent.py of each file a commit stages. All three load it by path, since
the hyphenated name cannot be imported.

This docstring is the scope doc-craft's Review section points to. A file is
documentation when it is Markdown and one of these holds:

  - its basename is CLAUDE.md, AGENTS.md or SKILL.md;
  - it is an agent definition, .claude/agents/*.md;
  - it is a workspace's README.md or sits under a workspace's docs/, where a
    workspace is the repo root or a project its .web-tools.json declares;
  - it matches a markdown glob of the repo's declared retrieval sources
    (skills/ or .claude/skills/file-retrieval/sources.csv), or, where the repo
    carries no such registry, one of FALLBACK.

A JSON file under a lists/ folder is documentation when its top-level object
has "edit": "propose": a list the owner signs off.

It is never documentation when it is written freely by design (chron/, blog/,
tracker/tasks/, a dump tray), is research the repo declares in .web-tools.json
(a declared path, or the folder of a declared README.md), or has no wording to
approve: .gitattributes gives it edit=regenerated, tool-written or write-once,
or its first lines carry a generated-file banner.

    governing-docs.py ROOT REL    prints the basis and exits 0 when REL is
                                  documentation in the checkout at ROOT, else 1
"""
import csv
import io
import json
import os
import re
import subprocess
import sys

ALWAYS = ("CLAUDE.md", "AGENTS.md", "SKILL.md")
FALLBACK = ["*.md", "skills/**/*.md", ".claude/skills/**/*.md"]
FREE = ("chron/", "blog/", "dump/", "tracker/tasks/")
NO_WORDING = ("regenerated", "tool-written", "write-once")
# A banner opens a line, alone or inside a comment: "<!-- generated by …",
# "Generated by `tool.py`; re-run rather than edit", "Do not hand-edit". Prose
# that only mentions generating, such as "do not hand-edit the CSV" in the file
# a CSV is built from, is not one.
GENERATED = re.compile(r"^\s*(?:<!--|[#>*_`]+)?\s*(?:(?:this file (?:is|was) )?(?:auto-?)?generated\b.*\b(?:from|by)\b|do not (?:hand-)?edit\b(?! the))",
                       re.I | re.M)


def glob_hit(rel, g):
    """`*` stays inside one folder and `**/` spans any number, none included;
    fnmatch lets `*` cross `/`, so the root-only `*.md` matched every file."""
    rx = re.escape(g).replace(r"\*\*/", "(?:[^/]+/)*").replace(r"\*", "[^/]*")
    return re.fullmatch(rx, rel) is not None


def _read(root, rel, staged):
    """The file's text from the working tree, or from the index when `staged`,
    which is what a commit gate measures. None when there is no such file."""
    if staged:
        r = subprocess.run(["git", "-C", root, "show", f":{rel}"], capture_output=True, text=True)
        return r.stdout if r.returncode == 0 else None
    try:
        with open(os.path.join(root, rel), encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError:
        return None


def _edit_policy(root, rel, staged):
    args = ["git", "-C", root, "check-attr"] + (["--cached"] if staged else []) + ["edit", "--", rel]
    try:
        out = subprocess.run(args, capture_output=True, text=True).stdout.strip()
    except OSError:
        return ""
    return out.rsplit(": ", 1)[-1] if out else ""


def _declarations(root, cache, staged):
    """(research paths, workspace roots, globs, basis), read once per root."""
    if "globs" in cache:
        return cache["research"], cache["workspaces"], cache["globs"], cache["basis"]
    try:
        manifest = json.loads(_read(root, ".web-tools.json", staged) or "{}")
    except ValueError:
        manifest = {}
    if not isinstance(manifest, dict):
        manifest = {}
    entries = lambda key: [e for e in manifest.get(key) or [] if isinstance(e, dict)]
    research = [(e.get("path") or "").strip("/") for e in entries("research")]
    workspaces = [""] + [(e.get("path") or "").strip("/") + "/" for e in entries("projects") if e.get("path")]
    globs, basis = [], "fallback globs"
    for d in ("skills", ".claude/skills"):
        text = _read(root, f"{d}/file-retrieval/sources.csv", staged) if root else None
        if text:
            try:
                globs = [r["glob"] for r in csv.DictReader(io.StringIO(text)) if (r.get("glob") or "").endswith(".md")]
            except (KeyError, csv.Error):
                globs = []
            if globs:
                basis = "the sources registry"
            break
    cache.update(research=research, workspaces=workspaces, globs=globs or FALLBACK, basis=basis)
    return research, workspaces, cache["globs"], basis


def _proposed_list(root, rel, staged):
    """A list whose header says changes to it are proposed, not made."""
    if not ("/" + rel).rsplit("/", 1)[0].endswith("/lists") or not root:
        return None
    if _edit_policy(root, rel, staged) in NO_WORDING:
        return None
    try:
        doc = json.loads(_read(root, rel, staged) or "null")
    except ValueError:
        return None
    return "a list the owner signs off" if isinstance(doc, dict) and doc.get("edit") == "propose" else None


def documentation(root, rel, cache=None, staged=False):
    """The basis on which `rel`, a path inside the checkout at `root`, is
    documentation, or None. A `cache` dict, kept across calls for one root,
    saves rereading the declarations; `staged` reads the index instead of the
    working tree, for a commit gate."""
    base = os.path.basename(rel)
    if not rel.endswith((".md", ".json")):
        return None
    if rel.startswith(FREE) or "/dump/" in rel:
        return None
    if rel.endswith(".json"):
        return _proposed_list(root, rel, staged)
    cache = {} if cache is None else cache
    research, workspaces, globs, basis = _declarations(root, cache, staged)
    if any(p and (rel == p or (os.path.basename(p) == "README.md" and os.path.dirname(p)
                              and rel.startswith(os.path.dirname(p) + "/"))) for p in research):
        return None
    if root and _edit_policy(root, rel, staged) in NO_WORDING:
        return None
    head = "".join((_read(root, rel, staged) or "").splitlines(True)[:8]) if root else ""
    if GENERATED.search(head):
        return None
    if base in ALWAYS:
        return "an agent contract or skill"
    if glob_hit(rel, ".claude/agents/*.md"):
        return "an agent definition"
    for ws in workspaces:
        if rel == ws + "README.md" or (rel.startswith(ws + "docs/") and rel.count("/") > ws.count("/")):
            return "a workspace's README or docs/"
    if any(glob_hit(rel, g) for g in globs):
        return basis
    return None


if __name__ == "__main__":
    basis = documentation(sys.argv[1], sys.argv[2]) if len(sys.argv) == 3 else None
    if basis:
        print(basis)
    sys.exit(0 if basis else 1)
