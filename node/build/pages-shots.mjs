#!/usr/bin/env node
// Regenerate pages/thumbs/*.png — one screenshot per page for the visual index.
//
//   node node/build/pages-shots.mjs            -> shoots every page
//   node node/build/pages-shots.mjs <page ...> -> shoots only the named pages
//   node node/build/pages-shots.mjs --stale    -> shoots nothing; names each page
//        with a pending change whose thumbnail has none, and exits 1 if any
//        (the thumbnails check in docs/commit-rules.csv)
//
// Each thumbnail is the page rendered headlessly by node/render/screenshot.mjs
// (Chromium, with CDN/own-code requests resolved to the local tree), captured at a
// uniform 16:10 viewport so the cards in pages/index.html line up. Output mirrors
// the pages/ tree under pages/thumbs/ (e.g. pages/foo.html -> pages/thumbs/foo.png).
//
// These PNGs are committed: pages/index.html (generated by pages-index.mjs) shows
// them as each card's default preview, with a live-iframe / source toggle on top.
// Re-run when a page is added or its look changes; then `npm run pages-index`.

import { readdir, mkdir, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WIDTH = 1000, HEIGHT = 625;            // 16:10, matches the card aspect ratio

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..');
const shotTool = path.join(here, '..', 'render', 'screenshot.mjs');

// Source roots, matching pages-index.mjs: pages/ itself, the kit demos that
// live under lib/kits/demos/, and the skill demos at skills/<name>/demo.html.
// `virt` is the thumbnail path prefix (so kit demos land in
// pages/thumbs/kit-demos/); `src` resolves the file to actually shoot. `pick`,
// as in pages-index.mjs, maps a file to its catalog name or null to skip it.
const SOURCES = [
  { dir: 'pages',           virt: '',          src: rel => path.join('pages', rel) },
  { dir: 'lib/kits/demos',  virt: 'kit-demos', src: rel => path.join('lib/kits/demos', rel) },
  { dir: 'skills',          virt: 'skill-demos', src: rel => path.join('skills', rel),
    pick: f => f.match(/^([^/]+)\/demo\.html$/)?.[1]?.concat('.html') ?? null },
];

// Which pages a run shoots. An argument names a page with or without its
// pages/ prefix and its .html, so `diff-tool`, `diff-tool.html` and
// `pages/diff-tool.html` all reach pages/diff-tool.html; a demo answers to its
// thumbnail path (kit-demos/note) or its source path (lib/kits/demos/note.html).
// No arguments select every page. Each argument that reaches nothing comes back
// in `unmatched`: names were once compared with .html still on, a bare name
// selected the empty set, and the run printed `0/0 ok` and exited 0 having
// shot nothing (snag pages-shots-vacuous-ok).
export function selectPages(pages, args) {
  if (!args.length) return { selected: pages, unmatched: [] };
  const bare = s => String(s).replace(/\\/g, '/').replace(/^\.\//, '').replace(/^pages\//, '').replace(/\.html$/, '');
  const hit = new Set(), unmatched = [];
  for (const a of args) {
    const found = pages.filter(p => bare(p.rel) === bare(a) || bare(p.src) === bare(a));
    if (found.length) for (const p of found) hit.add(p);
    else unmatched.push(a);
  }
  return { selected: pages.filter(p => hit.has(p)), unmatched };
}

async function walk(baseDir, dir = baseDir) {
  const out = [];
  for (const ent of await readdir(dir, { withFileTypes: true })) {
    if (ent.name === 'thumbs') continue;                       // never shoot the output dir
    const abs = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...await walk(baseDir, abs));
    else if (ent.name.endsWith('.html') && ent.name !== 'index.html') out.push(path.relative(baseDir, abs));
  }
  return out;
}

// Pages with a pending change whose thumbnail has none. Thumbnails are slow and
// not byte-deterministic, so no commit rule shoots them; this names what the
// once-a-session refresh should shoot.
function stale() {
  const status = (...specs) =>
    spawnSync('git', ['status', '--porcelain', '--', ...specs], { cwd: repoRoot, encoding: 'utf8' }).stdout || '';
  const lines = [];
  for (const entry of status(...SOURCES.map(s => s.dir + '/*.html')).split('\n').filter(Boolean)) {
    const file = entry.slice(3).replace(/.* -> /, '');
    const s = SOURCES.find(s => file.startsWith(s.dir + '/'));
    const f = file.slice(s.dir.length + 1);
    const v = path.posix.basename(f) === 'index.html' || f.startsWith('thumbs/') ? null : s.pick ? s.pick(f) : f;
    if (!v || !existsSync(path.join(repoRoot, file))) continue;
    const rel = s.virt ? `${s.virt}/${v}` : v;
    const thumb = `pages/thumbs/${rel.replace(/\.html$/, '.png')}`;
    if (!status(thumb).trim()) lines.push(`${file} changed but ${thumb} did not; refresh it at wrap-up: npm run pages-shots -- ${rel}`);
  }
  return lines;
}

// Run only as a script, so the suite can import selectPages without a browser.
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]) && process.argv.includes('--stale')) {
  const lines = stale();
  for (const l of lines) console.log(l);
  process.exit(lines.length ? 1 : 0);
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  // Collect { rel (virtual thumb key), src (file to shoot) } across every source.
  let pages = [];
  for (const s of SOURCES) {
    const files = await walk(path.join(repoRoot, s.dir));
    for (const f of files.map(f => f.split(path.sep).join('/'))) {
      const v = s.pick ? s.pick(f) : f;
      if (v) pages.push({ rel: s.virt ? `${s.virt}/${v}` : v, src: s.src(f) });
    }
  }
  pages.sort((a, b) => a.rel.localeCompare(b.rel));

  const { selected, unmatched } = selectPages(pages, process.argv.slice(2));
  if (unmatched.length) {
    for (const a of unmatched) console.error(`pages-shots: ${a} names no page`);
    process.exit(1);
  }
  pages = selected;

  const results = [];
  for (const { rel, src } of pages) {
    const out = path.join('pages', 'thumbs', rel.replace(/\.html$/, '.png'));
    await mkdir(path.dirname(path.join(repoRoot, out)), { recursive: true });
    process.stdout.write(`shooting ${rel} -> ${out} ... `);
    // A page can declare the query string of its representative shot, e.g.
    // <meta name="shot-query" content="repo=mehrlander/web-tools"> for a page
    // whose bare URL paints an auth/empty state instead of its real UI.
    const html = await readFile(path.join(repoRoot, src), 'utf8');
    const q = html.match(/<meta\s+name="shot-query"\s+content="([^"]*)"/);
    const r = spawnSync(process.execPath, [
      shotTool, src,
      '--out', out, '--width', String(WIDTH), '--height', String(HEIGHT),
      ...(q ? ['--query', q[1]] : []),
    ], { cwd: repoRoot, encoding: 'utf8' });
    const ok = r.status === 0;
    // Surface any [pageerror]/[fatal] lines so broken pages are visible, not silent.
    const flags = (r.stdout || '').split('\n').filter(l => /\[(pageerror|fatal|requestfailed)\]/.test(l));
    console.log(ok ? 'ok' : `FAILED (exit ${r.status})`);
    results.push({ rel, ok, flags });
  }

  console.log(`\n=== pages-shots: ${results.filter(r => r.ok).length}/${results.length} ok ===`);
  for (const r of results) {
    if (!r.ok) console.log(`  FAILED  ${r.rel}`);
    else if (r.flags.length) console.log(`  notes   ${r.rel}: ${r.flags.length} render warning(s)`);
  }
  process.exit(results.every(r => r.ok) ? 0 : 1);
}
