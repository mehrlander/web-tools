#!/usr/bin/env node
// Build a self-resolving offline form of a page's gh.load chain — "the build".
//
//   node tools/build/build.mjs <page-path>            -> dist/<page>.js
//
// The emit format lives in lib/build.js (window.buildKit.emit), shared with
// the in-browser baker (kits/bundle.js) so the two can't drift. This Node entry
// supplies a statically-walked cache (tools/build/graph.mjs) and writes dist/.
//
// What it emits is NOT a rewritten graph: it's the real gh-api.js loader with
// GH.prototype.get overridden by an inlined cache of every own-repo file the page
// reaches. The actual loader runs — same strip+wrap+execute, gh-boot registry,
// read() tracking — only the source bytes come from memory. Third-party libs stay
// on the page's CDN tags.
//
// The build and the runtime loader optimize opposite things: the loader is the
// fresh, per-file dev/review path; the build is a delivery snapshot. So a page
// adopts the build only at a boundary (baked into a downloadable page, or a
// versioned same-origin asset) — never back onto jsDelivr, whose cache the loader
// was written to avoid.
//
// dist/ is generated and mostly gitignored: rebuild on demand. The exception is
// a build a PAGE ADOPTS, which has to ship with the page and be held to its
// sources: dist/dictate.js is the one (pages/dictate.html imports it, the commit
// hook refreshes it, and --check below holds it). See tools/README.md.

import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildGraph } from './graph.mjs';
import { loadKit } from './kit-shim.mjs';

const REPO = 'mehrlander/web-tools';
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

const arg = process.argv[2];
if (!arg) {
  console.error('Usage: node tools/build/build.mjs <page-path>');
  process.exit(2);
}

let graph;
try {
  graph = buildGraph(repoRoot, arg);
} catch (e) {
  console.error(`build: ${e.message}`);
  process.exit(1);
}

const { buildKit } = loadKit(repoRoot, 'lib/build.js');
const ghApiSrc = await readFile(path.join(repoRoot, 'lib/gh-api.js'), 'utf8');

// graph.files -> the { 'lib/<path>': source } cache buildKit.emit expects.
const cache = Object.fromEntries(graph.files.map(f => [f.key, f.src]));

const baseName = path.basename(arg, path.extname(arg));
// NO DATE IN THE HEADER, and that is the difference between an artifact that
// can be tracked and one that cannot. A stamp makes every rebuild a different
// file, so the commit hook would restage it on every commit and the
// derived-artifacts check could never compare bytes. The one build that is
// tracked (dist/dictate.js, adopted by pages/dictate.html) needs both, and the
// stamp was telling nobody anything git does not already record. Same rule
// tools/build/build-app.mjs states for the app's build.
const header = `// dist/${baseName}.js — generated by tools/build/build.mjs. Do not edit.
// Offline form of ${arg}'s gh.load chain (the gh-api.js loader + an inlined source
// cache). Third-party libs stay on their CDN tags. Rebuild: node tools/build/build.mjs ${arg}

`;

const out = buildKit.emit({ ghApiSrc, cache, repo: REPO, defaultRef: graph.defaultRef, header });

const distDir = path.join(repoRoot, 'dist');
await mkdir(distDir, { recursive: true });
const outPath = path.join(distDir, `${baseName}.js`);

// --check compares bytes instead of writing, which is what lets a TRACKED build
// be held to its sources by tools/test/derived-artifacts.test.mjs. Most builds
// here are still on-demand and gitignored; the check costs nothing for those
// and is the whole gate for the one that is not.
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = await readFile(outPath, 'utf8'); } catch {}
  if (cur !== out) {
    console.error(`build: dist/${baseName}.js is stale — run \`node tools/build/build.mjs ${arg}\`.`);
    process.exit(1);
  }
  console.log(`build: dist/${baseName}.js is up to date.`);
  process.exit(0);
}

await writeFile(outPath, out);

const kb = (Buffer.byteLength(out) / 1024).toFixed(0);
console.log(`build: ${arg}`);
console.log(`  seeds (${graph.seeds.length}): ${graph.seeds.join(', ')}`);
console.log(`  cached own-code files (${graph.files.length}):`);
for (const f of graph.files.sort((a, b) => a.rel.localeCompare(b.rel))) {
  console.log(`    ${f.rel}  (${(f.src.length / 1024).toFixed(1)}k)`);
}
if (graph.misses.length) console.log(`  misses (not on disk): ${graph.misses.join(', ')}`);
console.log(`  -> ${path.relative(repoRoot, outPath)}  (${kb}k)`);
